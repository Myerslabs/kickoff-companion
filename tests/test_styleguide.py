@pytest.mark.skipif(shutil.which("node") is None, reason="node is not installed")
def test_every_javascript_module_parses(tmp_path):
    modules = sorted((STATIC_DIR / "js").rglob("*.js"))
    assert len(modules) >= 28
    for module in modules:
        target = tmp_path / (module.stem + ".mjs")
        target.write_text(module.read_text(encoding="utf-8"), encoding="utf-8")
        result = subprocess.run(["node", "--check", str(target)], capture_output=True, text=True, timeout=30)
        assert result.returncode == 0, f"{module.relative_to(PROJECT_ROOT)}: {result.stderr[:400]}"


