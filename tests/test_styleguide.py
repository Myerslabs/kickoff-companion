"""The design system: fonts self-hosted with the right type, the styleguide served, the
sample data generated from fixtures, and every JavaScript module at least parseable."""

from __future__ import annotations

import json
import re
import shutil
import subprocess

import pytest
from fastapi.testclient import TestClient

from app.config import PROJECT_ROOT, STATIC_DIR

FONTS = ["Barlow-400", "Barlow-500", "Barlow-600", "Barlow-700", "BarlowCondensed-500", "BarlowCondensed-600", "BarlowCondensed-700"]


def test_fonts_are_self_hosted_with_the_right_type(plain_client: TestClient):
    for name in FONTS:
        response = plain_client.get(f"/static/fonts/{name}.woff2", follow_redirects=False)
        assert response.status_code == 200, name
        assert response.headers["content-type"].startswith("font/woff2"), name
        assert response.content[:4] == b"wOF2", name
    assert (STATIC_DIR / "fonts" / "OFL.txt").exists()


def test_static_cache_headers(client: TestClient):
    assert client.get("/static/js/ui/dom.js").headers["cache-control"] == "no-cache"
    assert client.get("/static/css/tokens.css").headers["cache-control"] == "no-cache"
    assert client.get("/static/fonts/Barlow-400.woff2").headers["cache-control"] == "public, max-age=31536000, immutable"
    assert client.get("/").headers["cache-control"] == "no-cache"


def test_tokens_define_the_locked_palette_and_fonts():
    css = (STATIC_DIR / "css" / "tokens.css").read_text(encoding="utf-8")
    for token in ("--ground", "--panel", "--rule", "--chalk", "--fog", "--team-accent", "--team-primary", "--opp", "--good", "--stale", "--bad", "--replay"):
        assert f"{token}:" in css, token
    assert css.count("@font-face") == 7
    assert "../fonts/Barlow-400.woff2" in css
    assert "tabular-nums" in css
    assert "fonts.googleapis" not in css and "cdn" not in css.lower()


def test_no_third_party_urls_in_stylesheets_or_pages():
    for path in list((STATIC_DIR / "css").glob("*.css")) + list(STATIC_DIR.glob("*.html")):
        text = path.read_text(encoding="utf-8")
        assert "googleapis" not in text and "cdnjs" not in text and "unpkg" not in text, path.name


