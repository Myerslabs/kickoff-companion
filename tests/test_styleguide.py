def test_sample_data_module_is_served_and_real(plain_client: TestClient):
    response = plain_client.get("/static/js/sample-data.js", follow_redirects=False)
    assert response.status_code == 200
    assert "javascript" in response.headers["content-type"]
    assert response.text.startswith("// Generated by tools/make_sample_data.py")
    body = response.text.split("export const sample = ", 1)[1].rstrip().rstrip(";")
    data = json.loads(body)
    assert data["team"]["school"] == "Swampwater Tech"
    assert data["record"]["overall"]["wins"] >= 0
    assert len(data["schedule"]) == 12
    assert data["live"]["home"]["school"] and data["live"]["away"]["school"]
    assert len(data["live"]["drives"]) > 10 and len(data["live"]["plays"]) > 100
    assert data["program"]["them"]["school"]
    assert len(data["roster"]) > 80
    assert data["profile"]["rows"][0]["nationalRank"] >= 1
    # 2026-09-21 additions: quarter scores, success rates, recruiting join, newspaper slate
    assert len(data["live"]["lineScores"]["home"]) >= 4 and len(data["live"]["lineScores"]["away"]) >= 4
    for side in data["live"]["box"].values():
        assert 0 <= side["successRate"] <= 1 and side["successCounts"]["judged"] > 0
        assert side["drives"] >= 1 and side["explosive"]["twenty"] >= side["explosive"]["forty"]
    assert any(isinstance(play.get("success"), bool) for play in data["live"]["plays"])
    assert any(player.get("highSchool") and player.get("stars") for player in data["roster"])
    assert all("highSchool" in player and "stars" in player for player in data["roster"])
    assert len(data["recruiting"]["commits"]) >= 1 and set(data["recruiting"]["starCounts"]) == {"1", "2", "3", "4", "5"}
    assert data["newspaper"]["slate"][0]["isUs"] and data["newspaper"]["slate"][0]["home"]["school"]
    assert len(data["newspaper"]["slate"]) >= 5 and all(g["home"]["school"] and g["away"]["school"] for g in data["newspaper"]["slate"])
    assert any(len(rows) >= 2 for rows in data["rosterHistory"].values())
    assert set(data["profiles"]) >= {"Swampwater Tech", data["program"]["them"]["school"]}
    assert data["program"]["advanced"]["Swampwater Tech"]["offense"]["successRate"] > 0


def test_generator_rebuilds_the_same_module(tmp_path, monkeypatch):
    import tools.make_sample_data as generator

    monkeypatch.setattr(generator, "OUT", tmp_path / "sample-data.js")
    assert generator.main() == 0
    written = (tmp_path / "sample-data.js").read_text(encoding="utf-8")
    current = (STATIC_DIR / "js" / "sample-data.js").read_text(encoding="utf-8")
    assert written == current, "static/js/sample-data.js is out of date: run python tools/make_sample_data.py"


